import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Static scores use the same host adapter and contract as the application.
// Generated JS is a build output, never a separately maintained engine.
export async function buildBrowserSoundEngine(outputDir = path.join(root, "public/audio")) {
  await mkdir(outputDir, { recursive: true });
  for (const name of ["sound-engine", "physical-c4-worklet-engine"]) {
    const source = await readFile(path.join(root, "lib/audio", `${name}.ts`), "utf8");
    const { outputText } = ts.transpileModule(source, {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
    });
    await writeFile(path.join(outputDir, `${name}.js`),
      "// Generated by scripts/build-browser-sound-engine.mjs.\n" +
      outputText.replaceAll('"./sound-engine.ts"', '"./sound-engine.js"'));
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await buildBrowserSoundEngine();
  console.log("Wrote shared browser SoundEngine modules to public/audio");
}
